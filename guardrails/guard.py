#!/usr/bin/env python3
"""Claude Code guard hook. Config: guardrails.json in the project root.

Wired from `.claude/settings.json` with one subcommand per hook event:

  turn     UserPromptSubmit   Snapshots the working tree (git). At the end of the turn the hook
                              knows which files changed, no matter which tool changed them
                              (Edit, Bash, MCP, a subagent...).
  protect  PreToolUse (*)     Checks every tool call's write targets. Generated files and the
                              hook's own state are denied; protected paths and the guard setup
                              itself are sent to the user for approval. Role boundaries are
                              enforced for subagents (a test writer can't touch production
                              code, a reviewer can't write at all). Shell commands are parsed
                              heuristically for their write targets.
  record   PostToolUse        Notes edited files (covers projects without git).
  gates    Stop               Runs the gates triggered by files changed this turn. If a gate
                              fails, the turn can't end. It only blocks again when there was
                              progress since the last block, and at most `max_blocks` times.
Manual:
  check [--file PATH] [--command CMD] [--tool NAME] [--role NAME]
                              Validates the config and shows the decision for a file or command.

Hooks are a guardrail against accidents and shortcuts, not a security boundary: an indirect
write (writing a script and running it) can't be detected up front. The end-of-turn gates
(triggered by the changed files) and CI catch those.

No infrastructure problem (missing config, missing tool, timeout, script error) ever blocks a
tool or a turn. Claude Code reads exit code 2 as "block", so this script never exits with 2;
decisions are only made through JSON output.
"""

