def protect(event, cfg):
    d = protect_decision(event, cfg)
    if d:
        permission(*d)


def turn(event, cfg):
    """UserPromptSubmit: snapshot at the start of the turn. Prints nothing (it would go into context)."""
    cleanup_old()
    snap = git_snapshot()
    with state_lock(event):
        # edits recorded by a background subagent after the last Stop (not yet gated) carry over
        prev = read_state(event)
        new = {k: prev[k] for k in ("files", "edits") if k in prev}
        if snap:
            new["turn_start"] = snap
        write_state(event, new)


def record(event, cfg):
    tool_input = event.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return
    paths = [r for r in (relative(p) for p in path_values(tool_input)) if r not in (None, ".")]
    if not paths:
        return
    with state_lock(event):
        state = read_state(event)
        state["files"] = sorted(set(state.get("files", [])) | set(paths))[:5000]
        state["edits"] = int(state.get("edits", 0)) + 1
        write_state(event, state)


def environment(cfg):
    env = dict(os.environ)
    env["PATH"] = os.pathsep.join(cfg["extra_paths"] + [env.get("PATH", "")])
    return env


def argv_for(command, env):
    """argv to run; (None, tool name) if the tool isn't found."""
    if isinstance(command, str):
        return ["/bin/bash", "-c", command], None
    items = [str(x) for x in command]
    exe = shutil.which(items[0], path=env.get("PATH"))
    if exe is None:
        return None, items[0]
    return [exe] + items[1:], None


def missing_script(command):
    """A relative script path in a list command that doesn't exist. A wrong path makes the gate
    "could not run", not "failing": `python3 missing.py` exits 2 and would look like a real finding."""
    if isinstance(command, str):
        return None
    for arg in [str(x) for x in command][1:]:
        if arg.startswith("-") or os.path.isabs(arg) or not arg.endswith(SCRIPT_EXT):
            continue
        if not os.path.exists(os.path.join(ROOT, arg)):
            return arg
    return None


def run_gate(gate, cfg):
    env = environment(cfg)
    argv, missing = argv_for(gate["run"], env)
    if argv is None:
        return "infra", MSG["not_found"].format(tool=missing)
    script = missing_script(gate["run"])
    if script:
        return "infra", MSG["no_script"].format(path=script)
    try:
        p = subprocess.run(argv, cwd=ROOT, env=env, capture_output=True, encoding="utf-8",
                           errors="replace", timeout=gate["timeout"])
    except subprocess.TimeoutExpired:
        return "infra", MSG["timeout"].format(s=gate["timeout"])
    except OSError as e:
        return "infra", str(e)
    if p.returncode == 0:
        return "pass", ""
    output = (p.stdout or "") + ("\n" + p.stderr if p.stderr else "")
    if p.returncode in cfg["infra_exit_codes"]:
        tail = last_lines(output, 3)
        return "infra", MSG["exit"].format(code=p.returncode) + (f": {tail}" if tail else "")
    return "fail", last_lines(output, cfg["output_lines"]) or MSG["exit"].format(code=p.returncode)


def consume(event, seen):
    """Clears the state the gates just checked. An edit recorded by another agent while the gates
    were running (minutes) is kept, so the next Stop still checks it."""
    with state_lock(event):
        now = read_state(event)
        keep = {}
        if int(now.get("edits", 0)) != int(seen.get("edits", 0)):
            keep = {k: now[k] for k in ("files", "edits") if k in now}
        write_state(event, keep)


def gates(event, cfg):
    cleanup_old()
    with state_lock(event):
        state = read_state(event)
    snap = git_snapshot()
    changed = set(state.get("files", []))
    if state.get("turn_start") and snap:
        changed |= changed_between(state["turn_start"], snap)
    pending = [g for g in cfg["gates"] if any(matches(p, g["on"]) for p in changed)]
    if not pending:
        consume(event, state)
        return
    failing, warnings = [], []
    for g in pending:
        result, detail = run_gate(g, cfg)
        if result == "fail":
            failing.append((g["name"], detail))
        elif result == "infra":
            warnings.append(f"{g['name']}: {detail}")

    # Loop protection: block again only if the working tree changed since the last block (progress),
    # and at most `max_blocks` times per turn. stop_hook_active alone doesn't lift the block: if the
    # agent is trying to fix it, the gate checks again.
    blocks = int(state.get("blocks", 0))
    sig = signature(snap, state)
    progress = state.get("block_signature") != sig
    if failing and progress and blocks < cfg["max_blocks"]:
        with state_lock(event):
            new = read_state(event)  # keep records added while the gates ran
            new.update({"blocks": blocks + 1, "block_signature": sig})
            if "turn_start" in state:
                new.setdefault("turn_start", state["turn_start"])
            write_state(event, new)
        body = "\n\n".join(f"### {name}\n{detail}" for name, detail in failing)
        emit({"decision": "block", "reason": f"{MSG['failing']}\n\n{body}"})
        return

    consume(event, state)
    parts = []
    if failing:
        parts.append(MSG["still_failing"] + ":\n" + "\n\n".join(f"{n}:\n{d}" for n, d in failing))
    if warnings:
        parts.append(MSG["infra"] + ": " + " · ".join(warnings))
    if parts:
        emit({"systemMessage": "\n\n".join(parts)})


def concurrency_selftest(n=32):
    """The session state's concurrency contract, run with a temporary session in the real state folder."""
    problems = []
    event = {"session_id": "check-%d" % os.getpid()}
    try:
        procs = []
        for i in range(n):
            p = subprocess.Popen([sys.executable, os.path.abspath(__file__), "record"], stdin=subprocess.PIPE,
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                 env={**os.environ, "GUARDRAILS_ROOT": ROOT})
            p.stdin.write(json.dumps({**event, "tool_name": "Edit", "tool_input": {
                "file_path": os.path.join(ROOT, "race_check", "f%d" % i)}}).encode("utf-8"))
            p.stdin.close()
            procs.append(p)
        failed = sum(1 for p in procs if p.wait())
        s = read_state(event)
        if failed or len(s.get("files", [])) != n or s.get("edits") != n:
            problems.append(f"concurrent record: {len(s.get('files', []))} of {n} records kept, {failed} hook errors")
        seen = dict(s)
        with state_lock(event):  # another agent records while the gates run
            s = read_state(event)
            s.update({"files": s.get("files", []) + ["race_check/later"], "edits": n + 1})
            write_state(event, s)
        consume(event, seen)
        if "race_check/later" not in read_state(event).get("files", []):
            problems.append("a record that arrived while gates were running was consumed; the next Stop won't check it")
        turn(event, None)
        if "race_check/later" not in read_state(event).get("files", []):
            problems.append("a new turn dropped a pending (unchecked) record")
        consume(event, read_state(event))
        if os.path.exists(state_path(event)):
            problems.append("gates didn't clear the state they checked")
    finally:
        write_state(event, {})
        with contextlib.suppress(OSError):
            os.remove(state_path(event) + ".lock")
    return problems


def check(argv):
    ap = argparse.ArgumentParser(prog="guard.py check", description="Validates the guard config.")
    ap.add_argument("--file", help="decision for writing this file, and the gates it triggers")
    ap.add_argument("--command", help="decision for this shell command")
    ap.add_argument("--tool", default="Bash", help="tool name for --command (default Bash)")
    ap.add_argument("--role", help="decide as this subagent role")
    a = ap.parse_args(argv)
    print(f"project root : {ROOT}")
    print(f"config       : {CONFIG_PATH}")
    cfg, error = load_config()
    if error:
        print(f"PROBLEM: cannot read config: {error}")
        return 1
    if cfg is None:
        print("PROBLEM: no config file; the hooks do nothing")
        return 1
    print(f"state        : {state_dir()}")
    print(f"git          : {'yes (turn snapshots)' if git_snapshot() is not None else 'NO (only Edit/Write records trigger gates)'}")
    print(f"protected    : {len(cfg['generated_paths'])} generated paths · {len(cfg['stamps'])} stamps · "
          f"{len(cfg['ask_paths'])} ask paths · setup protection {'on' if cfg['protect_setup'] else 'OFF'}")
    print(f"commands     : {len(cfg['block'])} blocked · {len(cfg['ask'])} ask")
    print(f"roles        : {', '.join(cfg['roles']) or 'none'}")
    problems = list(cfg["problems"])
    # each rule's own examples: "match" must match and "no_match" must not
    for key in ("block", "ask"):
        for i, rule in enumerate(cfg[key]):
            for kind, expected in (("match", True), ("no_match", False)):
                for ex in rule["examples"].get(kind) or []:
                    if bool(rule["re"].search(str(ex))) != expected:
                        problems.append(f"{key}[{i}]: example {'did not match' if expected else 'matched by mistake'}: {ex}")
    if is_generated(relative(CONFIG_PATH), cfg):
        problems.append("the config file matches its own stamp patterns and would be treated as generated")
    env = environment(cfg)
    for g in cfg["gates"]:
        run = g["run"]
        if isinstance(run, str):
            try:
                first = shlex.split(run)[0]
            except (ValueError, IndexError):
                first = ""
            found = bool(first) and (shutil.which(first, path=env.get("PATH")) is not None or "/" in first
                                     or first in SHELL_BUILTINS)
        else:
            found = argv_for(run, env)[0] is not None
        print(f"gate         : {g['name']} · on {g['on_raw']} · run {run} · {'tool found' if found else 'TOOL NOT FOUND'}")
        if not found:
            problems.append(f"gate `{g['name']}`: the command's tool is not on PATH (add it to extra_paths)")
        script = missing_script(run)
        if script:
            problems.append(f"gate `{g['name']}`: `{script}` does not exist")
        if not g["on"]:
            problems.append(f"gate `{g['name']}`: no trigger globs, it never runs")
    if a.role and a.role not in cfg["roles"]:
        problems.append(f"role `{a.role}` is not defined in the config")
    names = {"deny": "DENIED", "ask": "ASKS USER"}
    if a.file:
        rel = relative(a.file)
        if rel is None:
            print(f"file         : {a.file} is outside the project")
        else:
            d = path_decision(rel, cfg, a.role if a.role in cfg["roles"] else None)
            print(f"file         : {rel} · write {names[d[0]] if d else 'allowed'}" + (f" · {d[1]}" if d else ""))
            triggered = [g["name"] for g in cfg["gates"] if matches(rel, g["on"])]
            print(f"               triggers gates: {', '.join(triggered) or 'none'}")
    if a.command is not None:
        event = {"tool_name": a.tool, "tool_input": {"command": a.command}, "cwd": ROOT}
        if a.role:
            event.update({"agent_id": "check", "agent_type": a.role})
        d = protect_decision(event, cfg)
        print(f"command      : {names[d[0]] if d else 'allowed'}" + (f" · {d[1]}" if d else ""))
    problems += concurrency_selftest()
    for p in problems:
        print(f"PROBLEM: {p}")
    if not problems:
        print("ok")
    return 1 if problems else 0


def main():
    sub = sys.argv[1] if len(sys.argv) > 1 else ""
    if sub == "check":
        return check(sys.argv[2:])
    handlers = {"protect": protect, "record": record, "gates": gates, "turn": turn}
    if sub not in handlers:
        print("usage: guard.py turn|protect|record|gates|check", file=sys.stderr)
        return 1
    try:
        event = json.load(sys.stdin)
    except ValueError:
        event = {}
    if not isinstance(event, dict):
        event = {}
    try:
        cfg, error = load_config()
        if error:
            if sub == "gates":
                emit({"systemMessage": MSG["bad_config"].format(error=error)})
            return 0
        if cfg is not None:
            handlers[sub](event, cfg)
        return 0
    except Exception:  # noqa: BLE001 — a hook must never end with a blocking exit code
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
