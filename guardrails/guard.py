# ── helpers ──────────────────────────────────────────────────────────────────


def emit(obj):
    sys.stdout.write(json.dumps(obj, ensure_ascii=False))


def glob_regex(pattern):
    """`**` any depth, `*` one path segment, `?` one character."""
    parts, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            parts.append("(?:.*/)?")
            i += 3
            continue
        if pattern.startswith("**", i):
            parts.append(".*")
            i += 2
            continue
        c = pattern[i]
        parts.append("[^/]*" if c == "*" else "[^/]" if c == "?" else re.escape(c))
        i += 1
    return re.compile("^" + "".join(parts) + "$")


def matches(rel, regexes):
    return any(r.match(rel) for r in regexes)


def relative(path):
    """Path relative to the project root ("." is the root); None if outside the project."""
    if not path or not isinstance(path, str):
        return None
    full = path if os.path.isabs(path) else os.path.join(ROOT, path)
    rel = os.path.relpath(os.path.realpath(full), os.path.realpath(ROOT))
    if rel == ".." or rel.startswith(".." + os.sep):
        return None
    return rel.replace(os.sep, "/")


def stamped(full, patterns):
    try:
        with open(full, encoding="utf-8", errors="replace") as f:
            for i, line in enumerate(f):
                if i >= 30:
                    break
                if any(p.search(line) for p in patterns):
                    return True
    except OSError:
        pass
    return False


def last_lines(text, n):
    return "\n".join([s for s in text.splitlines() if s.strip()][-n:])


def state_dir():
    """Inside .git when there is one (never committed), otherwise .claude/.guardrails."""
    git = os.path.join(ROOT, ".git")
    if os.path.isdir(git):
        return os.path.join(git, "guardrails")
    if os.path.isfile(git):  # worktree: ".git" is a file pointing to the real git dir
        try:
            with open(git, encoding="utf-8") as f:
                first = f.readline().strip()
            if first.startswith("gitdir:"):
                p = first[len("gitdir:"):].strip()
                return os.path.join(p if os.path.isabs(p) else os.path.join(ROOT, p), "guardrails")
        except OSError:
            pass
    return os.path.join(ROOT, ".claude", ".guardrails")


def literal_prefix(pattern):
    return re.split(r"[*?\[{]", pattern, maxsplit=1)[0]


# ── config ───────────────────────────────────────────────────────────────────


def load_config():
    """(config, error). No config file: (None, None) and the hooks do nothing."""
    if not os.path.isfile(CONFIG_PATH):
        return None, None
    try:
        with open(CONFIG_PATH, encoding="utf-8") as f:
            raw = json.load(f)
        if not isinstance(raw, dict):
            raise ValueError("the root must be a JSON object")
    except (OSError, ValueError) as e:
        return None, str(e)

    problems = []

    def compile_re(pattern, where):
        try:
            return re.compile(pattern)
        except (re.error, TypeError) as e:
            problems.append(f"{where}: invalid regular expression `{pattern}`: {e}")
            return None

    def rules(key):
        out = []
        for i, rule in enumerate(raw.get(key) or []):
            if not isinstance(rule, dict) or "pattern" not in rule:
                problems.append(f"{key}[{i}]: expected {{\"pattern\": ..., \"reason\": ...}}")
                continue
            r = compile_re(rule["pattern"], f"{key}[{i}]")
            if r is not None:
                examples = rule.get("examples") or {}
                if not isinstance(examples, dict):
                    problems.append(f"{key}[{i}].examples: expected {{\"match\": [...], \"no_match\": [...]}}")
                    examples = {}
                out.append({"re": r, "reason": rule.get("reason", ""), "examples": examples})
        return out

    generated = raw.get("generated") or {}
    custom = generated.get("stamp_patterns")
    if custom:
        stamps = [p for p in (compile_re(x, "generated.stamp_patterns") for x in custom) if p is not None]
        md_stamps = stamps
    else:
        stamps = [re.compile(x) for x in DEFAULT_STAMPS]
        md_stamps = [re.compile(x) for x in DEFAULT_MD_STAMPS]

    ask_paths = []
    for i, rule in enumerate(raw.get("ask_paths") or []):
        if not isinstance(rule, dict) or not isinstance(rule.get("glob"), str):
            problems.append(f"ask_paths[{i}]: expected {{\"glob\": \"...\", \"reason\": ...}}")
            continue
        ask_paths.append({"re": glob_regex(rule["glob"]), "glob": rule["glob"], "reason": rule.get("reason", "")})

    gates, names = [], set()
    for i, g in enumerate(raw.get("gates") or []):
        if not isinstance(g, dict) or not g.get("name") or not g.get("run"):
            problems.append(f"gates[{i}]: `name` and `run` are required")
            continue
        if g["name"] in names:
            problems.append(f"gates[{i}]: name `{g['name']}` is used twice")
            continue
        names.add(g["name"])
        on = g.get("on") or []
        gates.append({"name": g["name"], "on_raw": on, "on": [glob_regex(t) for t in on],
                      "run": g["run"], "timeout": g.get("timeout", 180)})

    roles = {}
    for name, r in (raw.get("roles") or {}).items():
        if not isinstance(r, dict):
            problems.append(f"roles.{name}: expected {{\"write\": [globs], \"note\": ...}}")
            continue
        write = r.get("write") or []
        roles[name] = {"write": [glob_regex(w) for w in write], "write_raw": write, "note": r.get("note", "")}

    state_rel = relative(state_dir())
    state_globs = [".claude/.guardrails/**"] + ([state_rel + "/**"] if state_rel not in (None, ".") else [])
    protect_setup = bool(raw.get("protect_setup", True))
    # "ask" by default; strict setups pick "deny" (then only a human edits the guard config).
    setup_decision = "deny" if raw.get("setup_decision") == "deny" else "ask"
    generated_paths = list(generated.get("paths", []))
    # For deleting or moving a folder: the literal prefixes of protected globs.
    prefixes = [(literal_prefix(d), "deny", "state") for d in state_globs]
    prefixes += [(literal_prefix(d), "deny", "generated") for d in generated_paths]
    prefixes += [(literal_prefix(k["glob"]), "ask", "ask_path") for k in ask_paths]
    if protect_setup:
        prefixes += [(literal_prefix(d), setup_decision, "setup") for d in SETUP_PATHS]

    return {
        "generated_paths": [glob_regex(p) for p in generated_paths],
        "stamps": stamps,
        "md_stamps": md_stamps,
        "regenerate": generated.get("regenerate") or "",
        "block": rules("block"),
        "ask": rules("ask"),
        "ask_paths": ask_paths,
        "state_paths": [glob_regex(d) for d in state_globs],
        "protect_setup": protect_setup,
        "setup_decision": setup_decision,
        "setup_paths": [glob_regex(d) for d in SETUP_PATHS],
        "protected_prefixes": prefixes,
        "gates": gates,
        "roles": roles,
        "max_blocks": max(1, int(raw.get("max_blocks", MAX_BLOCKS))),
        "infra_exit_codes": set(raw.get("infra_exit_codes", [3, 126, 127])),
        "extra_paths": [os.path.expanduser(p) for p in raw.get("extra_paths", [])],
        "output_lines": int(raw.get("output_lines", 40)),
        "problems": problems,
    }, None


# ── session state ────────────────────────────────────────────────────────────


def state_path(event):
    session = re.sub(r"[^A-Za-z0-9_-]", "_", str(event.get("session_id") or "no-session"))
    return os.path.join(state_dir(), f"session-{session}.json")


def read_state(event):
    try:
        with open(state_path(event), encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


@contextlib.contextmanager
def state_lock(event):
    """Read-modify-write of the session state in one process at a time. Subagents share the main
    session's id; without a lock, parallel agents overwrote each other's file lists and half-written
    JSON crashed the hook. The lock is held only while reading/writing, never while a gate runs."""
    if fcntl is None:
        yield
        return
    path = state_path(event) + ".lock"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "a") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            os.utime(path)  # so cleanup doesn't remove a lock in use
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


def write_state(event, state):
    path = state_path(event)
    if not state:
        with contextlib.suppress(OSError):
            os.remove(path)
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=os.path.basename(path) + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(state, f)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.remove(tmp)
        raise


def cleanup_old():
    folder = state_dir()
    try:
        now = time.time()
        for name in os.listdir(folder):
            p = os.path.join(folder, name)
            if now - os.path.getmtime(p) > 7 * 86400:
                os.remove(p)
    except OSError:
        pass


def git_snapshot():
    """Working tree signature: {"head": sha, "dirty": {path: [mtime_ns, size] | None}}.
    None when the project root is not the root of a git repository."""
    def git(*args):
        return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, timeout=8)
    try:
        top = git("rev-parse", "--show-toplevel")
        if top.returncode != 0 or os.path.realpath(top.stdout.decode().strip()) != os.path.realpath(ROOT):
            return None
        head = git("rev-parse", "-q", "--verify", "HEAD").stdout.decode().strip() or None
        status = git("status", "--porcelain=v1", "-z", "--untracked-files=all")
        if status.returncode != 0:
            return None
    except (OSError, subprocess.TimeoutExpired):
        return None
    dirty = {}
    fields = status.stdout.decode("utf-8", "replace").split("\0")
    i = 0
    while i < len(fields):
        field = fields[i]
        i += 1
        if len(field) < 4:
            continue
        code, path = field[:2], field[3:]
        if code[0] in "RC":
            i += 1  # the old path of a rename is a separate field
        try:
            st = os.stat(os.path.join(ROOT, path))
            dirty[path] = [st.st_mtime_ns, st.st_size]
        except OSError:
            dirty[path] = None
    return {"head": head, "dirty": dirty}


def changed_between(before, now):
    """Files whose content, status or commit changed between two snapshots."""
    prev = before.get("dirty") or {}
    changed = {p for p, v in now["dirty"].items() if prev.get(p, "absent") != v}
    changed |= {p for p in prev if p not in now["dirty"]}
    if before.get("head") and now.get("head") and before["head"] != now["head"]:
        try:
            r = subprocess.run(["git", "-C", ROOT, "diff", "--name-only", before["head"], now["head"]],
                               capture_output=True, timeout=8)
            changed |= {s for s in r.stdout.decode("utf-8", "replace").splitlines() if s}
        except (OSError, subprocess.TimeoutExpired):
            pass
    return changed


def signature(snapshot, state):
    """Progress measure: changes whenever the working tree changes (edit counter without git)."""
    if snapshot is None:
        return "e%d" % int(state.get("edits", 0))
    return hashlib.sha1(json.dumps(snapshot, sort_keys=True).encode("utf-8")).hexdigest()


# ── protection decisions ─────────────────────────────────────────────────────


def permission(decision, reason):
    emit({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": decision,
        "permissionDecisionReason": reason,
    }})


def is_generated(rel, cfg):
    # the config holds the stamp patterns as text; it must not count as generated because of them
    if rel == relative(CONFIG_PATH):
        return False
    patterns = cfg["md_stamps"] if rel.lower().endswith(MARKDOWN_EXT) else cfg["stamps"]
    return matches(rel, cfg["generated_paths"]) or stamped(os.path.join(ROOT, rel), patterns)


def path_decision(rel, cfg, role=None, maybe=False):
    """Decision for writing to a path: ("deny" | "ask", reason) or None."""
    prefix = MSG["maybe"].format(path=rel) if maybe else ""
    candidates = (rel, rel + "/")  # a "folder/**" glob also covers the folder itself
    if any(matches(c, cfg["state_paths"]) for c in candidates):
        return "deny", prefix + MSG["state"].format(path=rel)
    if is_generated(rel, cfg):
        reason = MSG["generated"].format(path=rel)
        if cfg["regenerate"]:
            reason += f": `{cfg['regenerate']}`"
        return ("ask" if maybe else "deny"), prefix + reason + "."
    if role is not None and role in cfg["roles"]:
        r = cfg["roles"][role]
        if not r["write"]:
            return ("ask" if maybe else "deny"), prefix + MSG["role_readonly"].format(role=role, path=rel)
        if not matches(rel, r["write"]):
            return ("ask" if maybe else "deny"), prefix + MSG["role"].format(
                role=role, path=rel, note=r["note"] or f"Allowed: {', '.join(r['write_raw'])}.").strip()
    for rule in cfg["ask_paths"]:
        if any(rule["re"].match(c) for c in candidates):
            return "ask", prefix + (rule["reason"] or MSG["ask_path"].format(path=rel))
    if cfg["protect_setup"] and any(matches(c, cfg["setup_paths"]) for c in candidates):
        return ("ask" if maybe else cfg["setup_decision"]), prefix + MSG["setup"].format(path=rel)
    return None


def folder_decision(rel, cfg, role=None):
    """A folder is deleted or moved: does it contain a protected glob?"""
    if role is not None and role in cfg["roles"]:
        d = path_decision(rel, cfg, role)
        if d:
            return d
    prefix = "" if rel in ("", ".") else rel.rstrip("/") + "/"
    for glob_prefix, decision, key in cfg["protected_prefixes"]:
        if glob_prefix.startswith(prefix) or (glob_prefix + "/").startswith(prefix):
            return decision, MSG[key].format(path=rel or ".")
    return None


def mask_quotes(text):
    """Replaces characters inside quotes with `x`, keeping positions (to find separators and redirects)."""
    out, quote, i = [], None, 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\" and quote == '"' and i + 1 < len(text):
                out.append("xx")
                i += 2
                continue
            if c == quote:
                quote = None
                out.append(c)
            else:
                out.append("\n" if c == "\n" else "x")
        else:
            if c == "\\" and i + 1 < len(text):
                out.append("xx")
                i += 2
                continue
            if c in "'\"":
                quote = c
            out.append(c)
        i += 1
    return "".join(out)


def split_heredocs(command):
    """(command without heredoc bodies, [body texts])."""
    lines, rest, bodies, i = command.split("\n"), [], [], 0
    while i < len(lines):
        line = lines[i]
        rest.append(line)
        m = HEREDOC.search(line)
        i += 1
        if m:
            body = []
            while i < len(lines) and lines[i].strip() != m.group(2):
                body.append(lines[i])
                i += 1
            bodies.append("\n".join(body))
            i += 1
    return "\n".join(rest), bodies


def segments(text):
    masked = mask_quotes(text)
    out, start = [], 0
    for m in SEPARATOR.finditer(masked):
        out.append(text[start:m.start()])
        start = m.end()
    out.append(text[start:])
    return [s.strip().strip("(){}").strip() for s in out if s.strip().strip("(){}").strip()]


def redirect_targets(segment):
    masked, targets = mask_quotes(segment), []
    for m in REDIRECT.finditer(masked):
        t = re.match(r"\"([^\"]*)\"|'([^']*)'|([^\s;&|<>()]+)", segment[m.end():])
        if t:
            targets.append(next(g for g in t.groups() if g is not None))
    return targets


def words(segment):
    try:
        lex = shlex.shlex(segment, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        raw = list(lex)
    except ValueError:
        raw = segment.split()
    out, skip = [], False
    for t in raw:
        if skip:
            skip = False
            continue
        if t and set(t) <= set("<>&|;()"):
            skip = ">" in t or "<" in t  # the redirect target is resolved separately
            continue
        out.append(t)
    return out


def non_options(args):
    out, after = [], False
    for a in args:
        if after or a == "-" or not a.startswith("-"):
            out.append(a)
        elif a == "--":
            after = True
    return out


def write_targets(name, args):
    """Path strings a command writes, deletes or moves directly."""
    plain = [a for a in non_options(args) if a]
    if name in ("cp", "install", "ln", "rsync", "scp", "ditto"):
        if "-t" in args:
            i = args.index("-t")
            return args[i + 1:i + 2]
        return plain[-1:] if len(plain) >= 2 else []
    if name in ("mv", "rm", "unlink", "truncate", "shred", "rmdir", "patch", "tee", "touch"):
        return plain
    if name in ("sed", "gsed", "perl", "ruby") and any(
            re.match(r"^-[a-zA-Z]*i", a) or a.startswith("--in-place") for a in args):
        return plain
    if name == "dd":
        return [a[3:] for a in args if a.startswith("of=")]
    if name in ("curl", "wget"):
        out = []
        for i, a in enumerate(args):
            if a in ("-o", "-O", "--output", "--output-document") and i + 1 < len(args):
                out.append(args[i + 1])
            elif a.startswith(("--output=", "--output-document=")):
                out.append(a.split("=", 1)[1])
        return out
    if name == "git" and plain:
        sub = plain[0]
        if sub in ("checkout", "restore", "rm", "mv"):
            if "--" in args:
                return args[args.index("--") + 1:]
            return plain[1:] if sub != "checkout" else []
        return []
    formatter = ("--write" in args or "--fix" in args
                 or (name in ("gofmt", "goimports", "clang-format", "swift-format") and ("-w" in args or "-i" in args))
                 or (name == "dart" and plain[:1] == ["format"] and "--output=none" not in args and "-o" not in args))
    if formatter:
        return [a for a in plain if os.path.splitext(a)[1]]
    return []


def resolve_path(raw, cwd):
    """Path text from a command → project-relative paths (env vars and globs expanded)."""
    if not raw or len(raw) > 1000 or "\n" in raw:
        return []
    p = raw
    for name, value in {"CLAUDE_PROJECT_DIR": ROOT, "PWD": cwd, "HOME": os.path.expanduser("~")}.items():
        p = p.replace("${%s}" % name, value).replace("$" + name, value)
    p = os.path.expanduser(p)
    if not os.path.isabs(p):
        p = os.path.join(cwd, p)
    candidates = [p]
    if any(c in p for c in "*?["):
        candidates = glob.glob(p)[:500] + [p]
    return [r for r in (relative(c) for c in candidates) if r is not None]


def command_decisions(command, cwd, cfg, role=None):
    """Decisions from a shell command's write targets (heuristic, accident prevention)."""
    out = []
    text, bodies = split_heredocs(command)
    for seg in segments(text):
        ws = words(seg)
        i = 0
        while i < len(ws) and (re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", ws[i]) or os.path.basename(ws[i]) in COMMAND_PREFIXES):
            i += 1
            while i < len(ws) and ws[i].startswith("-"):
                i += 1
        name = os.path.basename(ws[i]) if i < len(ws) else ""
        args = ws[i + 1:]
        if name == "cd" and args:
            target = resolve_path(args[0], cwd)
            if target and os.path.isdir(os.path.join(ROOT, target[0])):
                cwd = os.path.normpath(os.path.join(ROOT, target[0]))
            continue
        deleting = name in ("rm", "rmdir", "mv", "shred", "unlink") or (name == "git" and args[:1] in (["rm"], ["mv"]))
        for raw in redirect_targets(seg) + write_targets(name, args):
            for rel in resolve_path(raw, cwd):
                if rel in ("/dev/null",):
                    continue
                if deleting and os.path.isdir(os.path.join(ROOT, rel)):
                    d = folder_decision(rel, cfg, role)
                else:
                    d = path_decision(rel, cfg, role)
                if d:
                    out.append(d)
        if name in INTERPRETERS:
            codes = list(bodies) if "<<" in seg else []
            for j, a in enumerate(args):
                if a in ("-c", "-e", "-E", "--eval", "-pe", "-ne") and j + 1 < len(args):
                    codes.append(args[j + 1])
            for code in codes:
                if not WRITE_API.search(code):
                    continue
                for literal in STRING_LITERAL.findall(code):
                    for rel in resolve_path(literal, cwd):
                        d = path_decision(rel, cfg, role, maybe=True)
                        if d:
                            out.append(("ask", d[1]))
    return out


def path_values(tool_input):
    out = []
    for key in PATH_KEYS:
        v = tool_input.get(key)
        if isinstance(v, str):
            out.append(v)
        elif isinstance(v, list):
            out += [x for x in v if isinstance(x, str)]
    return out


def role_of(event, cfg):
    """The subagent's role (its agent type), when it has rules in the config."""
    if not event.get("agent_id"):
        return None
    role = str(event.get("agent_type") or "")
    return role if role in cfg["roles"] else None


def protect_decision(event, cfg):
    tool = str(event.get("tool_name") or "")
    tool_input = event.get("tool_input") or {}
    if tool in READ_TOOLS or not isinstance(tool_input, dict):
        return None
    role = role_of(event, cfg)
    decisions = []
    command = next((tool_input[k] for k in COMMAND_KEYS if isinstance(tool_input.get(k), str)), None)
    if command is not None:
        for rule in cfg["block"]:
            if rule["re"].search(command):
                decisions.append(("deny", rule["reason"] or MSG["blocked"]))
        for rule in cfg["ask"]:
            if rule["re"].search(command):
                decisions.append(("ask", rule["reason"] or MSG["ask"]))
        decisions += command_decisions(command, os.path.realpath(str(event.get("cwd") or ROOT)), cfg, role)
    if tool in EDIT_TOOLS or (command is None and WRITE_VERB.search(tool)):
        for p in path_values(tool_input):
            rel = relative(p)
            if rel is not None:
                d = path_decision(rel, cfg, role)
                if d:
                    decisions.append(d)
    if not decisions:
        return None
    return next((d for d in decisions if d[0] == "deny"), decisions[0])


